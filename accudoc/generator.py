    def _generate_api_documentation(self) -> str:
        """Generate API documentation section."""
        api_docs = self.repo_info.get('api_docs', {})
        
        if not api_docs or not any(api_docs.values()):
            return ""
        
        sections = ["## API Documentation\n"]
        
        # Document classes
        classes = api_docs.get('classes', [])
        if classes:
            sections.append("### Classes\n")
            for cls in classes[:10]:  # Limit to 10
                sections.append(f"#### `{cls['name']}`")
                sections.append(f"*Defined in: `{cls['file']}` (line {cls['line']})*\n")
                if cls.get('docstring'):
                    sections.append(cls['docstring'] + "\n")
                else:
                    sections.append("*No documentation available*\n")
        
        # Document functions
        functions = api_docs.get('functions', [])
        if functions:
            sections.append("### Functions\n")
            for func in functions[:15]:  # Limit to 15
                params = func['params'] if func['params'] else ''
                sections.append(f"#### `{func['name']}({params})`")
                sections.append(f"*Defined in: `{func['file']}` (line {func['line']})*\n")
                if func.get('docstring'):
                    sections.append(func['docstring'] + "\n")
                else:
                    sections.append("*No documentation available*\n")
        
        # Document methods (only if not too many)
        methods = api_docs.get('methods', [])
        if methods and len(methods) <= 20:
            sections.append("### Methods\n")
            for method in methods[:20]:  # Limit to 20
                class_name = method.get('class', 'Unknown')
                params = method['params'] if method['params'] else ''
                sections.append(f"#### `{class_name}.{method['name']}({params})`")
                sections.append(f"*Defined in: `{method['file']}` (line {method['line']})*\n")
                if method.get('docstring'):
                    sections.append(method['docstring'] + "\n")
                else:
                    sections.append("*No documentation available*\n")
        
        return '\n'.join(sections)
    
