    def _generate_project_structure(self) -> str:
        """Generate project structure section."""
        sections = ["## Project Structure\n"]
        
        files = self.repo_info.get('files', [])
        if not files:
            return "## Project Structure\n\n*Project structure information not available.*"
            
        sections.append("```")
        
        # Create a tree-like structure
        tree = {}
        for file in files[:50]:  # Limit to first 50 files
            parts = file.split('/')
            current = tree
            for part in parts:
                if part not in current:
                    current[part] = {}
                current = current[part]
                
        def print_tree(node, prefix="", is_last=True):
            items = list(node.keys())
            result = []
            for i, item in enumerate(items):
                is_last_item = i == len(items) - 1
                connector = "└── " if is_last_item else "├── "
                result.append(f"{prefix}{connector}{item}")
                
                if node[item]:  # Has children
                    extension = "    " if is_last_item else "│   "
                    result.extend(print_tree(node[item], prefix + extension, is_last_item))
            return result
            
        tree_lines = print_tree(tree)
        sections.extend(tree_lines[:100])  # Limit output
        
        if len(files) > 50:
            sections.append(f"\n... and {len(files) - 50} more files")
            
        sections.append("```")
        
        # Documentation files
        docs = self.repo_info.get('documentation', [])
        if docs:
            sections.append("\n### Key Documentation Files\n")
            for doc in docs[:10]:
                sections.append(f"- `{doc}`")
                
        return '\n'.join(sections)
        
