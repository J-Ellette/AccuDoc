    def _generate_import_analysis(self) -> str:
        """Generate import analysis section."""
        imports = self.repo_info.get('imports', {})
        
        if not imports or not any(imports.values()):
            return ""
        
        sections = ["## Import Analysis\n"]
        sections.append("Analysis of module and package imports:\n")
        
        for lang, lang_imports in imports.items():
            if lang_imports:
                lang_name = lang.capitalize()
                sections.append(f"\n### {lang_name} Imports\n")
                sections.append(f"Most frequently imported modules:\n")
                
                # Show top imports
                sorted_imports = sorted(lang_imports.items(), key=lambda x: x[1], reverse=True)[:15]
                for module, count in sorted_imports:
                    sections.append(f"- `{module}` ({count} times)")
        
        return '\n'.join(sections)
    
