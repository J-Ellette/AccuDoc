"""Document generator module for creating documentation from repository info."""

from typing import Dict, List, Optional
from datetime import datetime
from pathlib import Path


class DocumentGenerator:
    """Generates documentation from scanned repository information."""
    
    def __init__(self, repo_info: Dict, template: str = 'default'):
        """
        Initialize the generator.
        
        Args:
            repo_info: Dictionary containing repository information
            template: Template to use for generation (default, minimal, detailed, api, readme)
        """
        self.repo_info = repo_info
        self.template_name = template
    
    def generate_and_export(self, output_path: str, format: str = 'markdown', 
                           title: Optional[str] = None, theme: str = "default",
                           markdown_flavor: str = "github", template: Optional[str] = None,
                           language: str = 'en') -> str:
        """
        Generate documentation and export to specified format.
        
        Args:
            output_path: Output file path
            format: Output format (markdown, html, txt)
            title: Document title (defaults to repository name)
            theme: Theme for HTML export (default, dark, minimal, corporate)
            markdown_flavor: Markdown flavor for markdown export (github, gitlab, commonmark)
            template: Template to use (overrides instance template)
            language: Language for documentation (en, es, fr, de, zh, ja, ar)
            
        Returns:
            Path to generated file
        """
        from accudoc.exporters import DocumentExporter
        from accudoc.doc_translator import DocumentTranslator
        
        # Generate markdown content
        content = self.generate_all(template_name=template)
        
        # Translate content if language is not English
        if language != 'en' and DocumentTranslator.is_supported(language):
            translator = DocumentTranslator(target_language=language)
            content = translator.translate_with_note(content)
        
        # Use repo name as title if not provided
        if title is None:
            title = f"{self.repo_info['name']} - Documentation"
        
        # Export to desired format
        return DocumentExporter.export(content, output_path, format=format, 
                                      title=title, theme=theme, 
                                      markdown_flavor=markdown_flavor)
        
    def generate_all(self, template_name: Optional[str] = None) -> str:
        """
        Generate all documentation sections using specified template.
        
        Args:
            template_name: Template to use (overrides instance template if provided)
        
        Returns:
            Complete documentation as a string
        """
        from accudoc.templates import TemplateManager
        
        # Use provided template or instance template
        tpl_name = template_name or self.template_name
        
        # Get template
        template_manager = TemplateManager()
        try:
            template = template_manager.get_template(tpl_name)
        except ValueError:
            # Fallback to default if template not found
            template = template_manager.get_template('default')
        
        # Generate sections based on template
        sections = []
        for section in template.get_sections():
            method_name = section['method']
            if hasattr(self, method_name):
                method = getattr(self, method_name)
                result = method()
                if result:
                    sections.append(result)
        
        return '\n\n'.join(filter(None, sections))
        
    def _generate_header(self) -> str:
        """Generate documentation header."""
        name = self.repo_info.get('name', 'Repository')
        header = [f"# {name}\n"]
        
        # Add badges if available
        badges = self.repo_info.get('badges', [])
        if badges:
            badge_line = []
            for badge in badges:
                badge_line.append(f"![{badge['label']}]({badge['url']})")
            header.append(' '.join(badge_line) + "\n")
        
        header.append(f"*Documentation generated by AccuDoc on {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}*\n")
        header.append("---\n")
        
        return '\n'.join(header)
        
    def _generate_overview(self) -> str:
        """Generate overview section."""
        sections = ["## Overview\n"]
        
        # Add existing README content if available
        if self.repo_info.get('readme_content'):
            sections.append("### Existing Documentation\n")
            readme = self.repo_info['readme_content']
            # Limit length if too long
            if len(readme) > 1000:
                readme = readme[:1000] + "...\n\n*(Truncated for brevity)*"
            sections.append(readme)
        else:
            sections.append(f"This repository contains the **{self.repo_info['name']}** project.")
            
        # Add git information
        git_info = self.repo_info.get('git_info', {})
        if git_info:
            sections.append("\n### Repository Information\n")
            if 'remote_url' in git_info:
                sections.append(f"- **Repository URL:** {git_info['remote_url']}")
            if 'branch' in git_info:
                sections.append(f"- **Current Branch:** {git_info['branch']}")
            
            # Show branches
            branches = git_info.get('branches', [])
            if branches:
                local_branches = [b for b in branches if not b.startswith('remotes/')]
                if local_branches:
                    sections.append(f"- **Branches:** {len(local_branches)} ({', '.join(local_branches[:5])})")
                    if len(local_branches) > 5:
                        sections.append(f"  - *...and {len(local_branches) - 5} more*")
            
            # Show tags
            tags = git_info.get('tags', [])
            if tags:
                sections.append(f"- **Tags:** {len(tags)} ({', '.join(tags[:5])})")
            
            # Show submodules
            submodules = git_info.get('submodules', [])
            if submodules:
                sections.append(f"- **Submodules:** {len(submodules)}")
                for submod in submodules[:5]:
                    sections.append(f"  - `{submod['path']}`")
                if len(submodules) > 5:
                    sections.append(f"  - *...and {len(submodules) - 5} more*")
            
            if 'last_commit' in git_info:
                sections.append(f"- **Last Commit:** {git_info['last_commit']}")
                
        return '\n'.join(sections)
        
