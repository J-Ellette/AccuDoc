    def _generate_changelog(self) -> str:
        """Generate changelog from git commits."""
        git_info = self.repo_info.get('git_info', {})
        commits = git_info.get('recent_commits', [])
        
        if not commits:
            return "## Changelog\n\n*No git history available.*"
        
        sections = ["## Changelog\n"]
        sections.append("Recent changes to this repository:\n")
        
        # Group commits by date
        from collections import defaultdict
        commits_by_date = defaultdict(list)
        for commit in commits:
            commits_by_date[commit['date']].append(commit)
        
        # Generate changelog entries
        for date in sorted(commits_by_date.keys(), reverse=True):
            sections.append(f"\n### {date}\n")
            for commit in commits_by_date[date]:
                sections.append(f"- **{commit['hash']}** {commit['message']} (*{commit['author']}*)")
        
        return '\n'.join(sections)
    
