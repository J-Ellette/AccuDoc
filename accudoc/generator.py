    def _generate_code_statistics(self) -> str:
        """Generate detailed code statistics section."""
        code_stats = self.repo_info.get('code_stats', {})
        
        if not code_stats or code_stats.get('total_lines', 0) == 0:
            return ""
        
        sections = ["## Code Statistics\n"]
        
        # Overall statistics
        sections.append("### Overall Statistics\n")
        sections.append(f"- **Total Lines:** {code_stats['total_lines']:,}")
        sections.append(f"- **Code Lines:** {code_stats['code_lines']:,}")
        sections.append(f"- **Comment Lines:** {code_stats['comment_lines']:,}")
        sections.append(f"- **Blank Lines:** {code_stats['blank_lines']:,}")
        sections.append(f"- **Files Analyzed:** {code_stats['file_count']}")
        
        # Calculate percentages
        total = code_stats['total_lines']
        if total > 0:
            code_pct = (code_stats['code_lines'] / total) * 100
            comment_pct = (code_stats['comment_lines'] / total) * 100
            blank_pct = (code_stats['blank_lines'] / total) * 100
            sections.append(f"\n**Code Distribution:**")
            sections.append(f"- Code: {code_pct:.1f}%")
            sections.append(f"- Comments: {comment_pct:.1f}%")
            sections.append(f"- Blank: {blank_pct:.1f}%")
        
        # Per-language statistics
        by_language = code_stats.get('by_language', {})
        if by_language:
            sections.append("\n### Statistics by Language\n")
            sections.append("| Language | Files | Total Lines | Code Lines | Comment Lines |")
            sections.append("|----------|-------|-------------|------------|---------------|")
            
            for lang in sorted(by_language.keys()):
                stats = by_language[lang]
                sections.append(
                    f"| {lang} | {stats['files']} | {stats['total_lines']:,} | "
                    f"{stats['code_lines']:,} | {stats['comment_lines']:,} |"
                )
        
        return '\n'.join(sections)
    
